/**
 * สร้าง typed catalog ของ Stored Procedure จาก definition จริง
 *   npm run codegen:sp
 * ที่มา: docs/reference/db-export/sp-by-schema/*.md (มีบรรทัดครบ) และ CMS_DB_2.1_SP_definitions.csv (SP ที่เหลือ)
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { parseCsv } from './csv';
import { toCamel } from './naming';

const ROOT = join(__dirname, '..', '..');
const DB = join(ROOT, 'docs', 'reference', 'db-export');

interface P {
  name: string;
  sqlType: string;
  required: boolean;
  output: boolean;
}
interface Sp {
  schema: string;
  name: string;
  params: P[];
}

function tsType(sql: string): string {
  const t = sql.toUpperCase().replace(/\(.*\)/, '');
  if (['INT', 'SMALLINT', 'TINYINT', 'FLOAT', 'REAL'].includes(t)) return 'number';
  if (['BIGINT', 'DECIMAL', 'NUMERIC', 'MONEY'].includes(t)) return 'number | string';
  if (t === 'BIT') return 'boolean';
  if (['DATETIME', 'DATETIME2', 'DATE', 'SMALLDATETIME'].includes(t)) return 'Date';
  if (['VARBINARY', 'BINARY'].includes(t)) return 'Buffer';
  return 'string';
}

function parseHeader(text: string): {
  schema?: string;
  name?: string;
  params: P[];
  unsupported: boolean;
} {
  const t = text
    .replace(/\/\*[\s\S]*?\*\//g, ' ')
    .replace(/--[^\n]*/g, (m) => (text.includes('\n') ? ' ' : m));
  const m = /(?:CREATE|ALTER)\s+(?:OR\s+ALTER\s+)?PROC(?:EDURE)?\s+\[?(\w+)\]?\.\[?(\w+)\]?/i.exec(
    t,
  );
  if (!m) return { params: [], unsupported: true };
  const rest = t.slice(m.index + m[0].length);
  const asM =
    /(?:^|\s)AS\s*(?=\s*(?:BEGIN|SET|DECLARE|SELECT|IF|WITH|INSERT|UPDATE|DELETE|EXEC|RETURN|--)|\r?\n)/i.exec(
      rest,
    );
  const head = asM ? rest.slice(0, asM.index) : rest.slice(0, 800);
  const params: P[] = [];
  const re =
    /@(\w+)\s+([A-Za-z_][\w.]*(?:\s*\(\s*(?:\d+|MAX)(?:\s*,\s*\d+)?\s*\))?)\s*(READONLY)?\s*(?:=\s*('[^']*'|[^,\s)]+))?\s*(OUTPUT|OUT\b)?/gi;
  let unsupported = false;
  for (const pm of head.matchAll(re)) {
    if (pm[3]) unsupported = true;
    params.push({
      name: pm[1],
      sqlType: pm[2].replace(/\s+/g, '').toUpperCase(),
      required: pm[4] === undefined,
      output: !!pm[5],
    });
  }
  return { schema: m[1], name: m[2], params, unsupported };
}

function main() {
  const sps = new Map<string, Sp>();
  const skipped: string[] = [];
  // 1) md (มีบรรทัด) ลำดับความสำคัญสูงสุด
  const mdDir = join(DB, 'sp-by-schema');
  for (const f of readdirSync(mdDir).filter((x) => x.endsWith('.md'))) {
    const blocks = readFileSync(join(mdDir, f), 'utf8').split(/^USE \[CMS_DB\]\s*$/m);
    for (const b of blocks) {
      const h = parseHeader(b);
      if (!h.schema || !h.name) continue;
      if (h.unsupported) skipped.push(`${h.schema}.${h.name}`);
      else sps.set(`${h.schema}.${h.name}`, { schema: h.schema, name: h.name, params: h.params });
    }
  }
  // 2) csv สำหรับตัวที่เหลือ
  for (const r of parseCsv(readFileSync(join(DB, 'CMS_DB_2.1_SP_definitions.csv'), 'utf8'))) {
    const key = `${r[0]}.${r[1]}`;
    if (sps.has(key)) continue;
    const h = parseHeader(r[2]);
    if (h.unsupported) skipped.push(key);
    else sps.set(key, { schema: r[0], name: r[1], params: h.params });
  }

  const bySchema = new Map<string, Sp[]>();
  for (const sp of sps.values()) bySchema.set(sp.schema, [...(bySchema.get(sp.schema) ?? []), sp]);

  const out: string[] = [];
  out.push('/* eslint-disable */');
  out.push(
    '// <auto-generated> สร้างโดย tools/codegen/generate-sp-catalog.ts จาก docs/reference/db-export — อย่าแก้มือ',
  );
  out.push("import { defineSp } from './sp.types';");
  out.push('');
  const tree: string[] = [];
  for (const [schema, list] of [...bySchema].sort((a, b) => a[0].localeCompare(b[0]))) {
    const seen = new Set<string>();
    const entries: string[] = [];
    for (const sp of list.sort((a, b) => a.name.localeCompare(b.name))) {
      const key = toCamel(sp.name.replace(/^sp_/i, ''));
      if (seen.has(key)) throw new Error(`ชื่อซ้ำ ${schema}.${key}`);
      seen.add(key);
      const typeName =
        `${schema.charAt(0).toUpperCase()}${schema.slice(1)}${key.charAt(0).toUpperCase()}${key.slice(1)}`.replace(
          /[^A-Za-z0-9]/g,
          '',
        );
      const ins = sp.params.filter((p) => !p.output);
      const outs = sp.params.filter((p) => p.output);
      out.push(`export interface ${typeName}In {`);
      for (const p of ins)
        out.push(`  ${p.name}${p.required ? '' : '?'}: ${tsType(p.sqlType)} | null;`);
      out.push('}');
      out.push(`export interface ${typeName}Out {`);
      for (const p of outs) out.push(`  ${p.name}: ${tsType(p.sqlType)} | null;`);
      out.push('}');
      const meta = sp.params
        .map(
          (p) =>
            `{ name: '${p.name}', sqlType: '${p.sqlType}', required: ${p.required}, output: ${p.output} }`,
        )
        .join(', ');
      entries.push(
        `    ${key}: defineSp<${typeName}In, ${typeName}Out>('${schema}.${sp.name}', [${meta}]),`,
      );
    }
    tree.push(`  ${schema.toLowerCase()}: {\n${entries.join('\n')}\n  },`);
  }
  out.push('');
  out.push(
    '/** catalog ของ Stored Procedure ทั้งหมดใน CMS_DB (Sp.<schema>.<ชื่อ camelCase ไม่รวม sp_>) */',
  );
  out.push(`export const Sp = {\n${tree.join('\n')}\n} as const;`);
  out.push('');
  writeFileSync(join(ROOT, 'src', 'database', 'sp', 'sp-catalog.generated.ts'), out.join('\n'));
  console.log(
    `generated ${sps.size} SP definitions; skipped (TVP/unsupported): ${skipped.join(', ') || '-'}`,
  );
}

main();
